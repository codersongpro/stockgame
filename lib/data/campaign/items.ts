export function getItemDefinition(itemId: string): ItemDefinition | undefined {
  return ITEM_DEFINITIONS.find((item) => item.id === itemId);
}

export function availableItemsForLevel(level: Level): ItemDefinition[] {
  const levelIndex = LEVEL_ORDER.indexOf(level);
  return ITEM_DEFINITIONS.filter((item) => LEVEL_ORDER.indexOf(item.levelMin) <= levelIndex);
}

export function isItemAllowedForLevel(item: ItemDefinition, level: Level): boolean {
  return LEVEL_ORDER.indexOf(item.levelMin) <= LEVEL_ORDER.indexOf(level);
}
